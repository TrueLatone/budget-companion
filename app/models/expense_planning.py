"""SQLAlchemy models for Expense Planning & Smart Check-in (F07-F13).

These tables are owned by the expenses module. Keep IDs generated by the module
in the ``ddmmyyyy-uniqueid`` format; external IDs owned by Budget/M1 must be
stored verbatim in ``source_expense_id``.
"""

from datetime import datetime, timezone

from sqlalchemy import Index, text

from app.extensions import db


def utcnow() -> datetime:
    """Return a naive UTC timestamp (portable across SQLite and PostgreSQL)."""
    return datetime.now(timezone.utc).replace(tzinfo=None)


class ExpensePlanItem(db.Model):
    """A recurring/one-off expense template received from M1 or the demo form."""

    __tablename__ = "expense_plan_items"

    plan_item_id = db.Column(db.String(21), primary_key=True)
    source_expense_id = db.Column(db.String(128), nullable=True)
    user_id = db.Column(db.String(64), nullable=False, index=True)
    title = db.Column(db.String(200), nullable=False)
    amount_source = db.Column(db.String(20), nullable=False, default="USER_ENTERED")
    planned_amount = db.Column(db.BigInteger, nullable=False)
    priority = db.Column(db.String(2), nullable=False, default="P1")
    schedule_tag = db.Column(db.String(20), nullable=False)
    day_of_week = db.Column(db.SmallInteger, nullable=True)
    day_of_month = db.Column(db.SmallInteger, nullable=True)
    specific_date = db.Column(db.Date, nullable=True)
    is_active = db.Column(db.Boolean, nullable=False, default=True)
    is_demo = db.Column(db.Boolean, nullable=False, default=True)
    created_at = db.Column(db.DateTime, nullable=False, default=utcnow)
    updated_at = db.Column(db.DateTime, nullable=False, default=utcnow, onupdate=utcnow)

    tasks = db.relationship("AssignedExpenseTask", back_populates="plan_item")

    __table_args__ = (
        Index(
            "uq_expense_plan_items_source",
            "user_id",
            "source_expense_id",
            unique=True,
            postgresql_where=text("source_expense_id IS NOT NULL"),
            sqlite_where=text("source_expense_id IS NOT NULL"),
        ),
    )

    def __repr__(self) -> str:  # pragma: no cover - debugging helper
        return f"<ExpensePlanItem {self.plan_item_id} {self.title!r}>"


class AssignedExpenseTask(db.Model):
    """A single scheduled occurrence of an expense plan item."""

    __tablename__ = "assigned_expense_tasks"

    task_id = db.Column(db.String(21), primary_key=True)
    plan_item_id = db.Column(
        db.String(21),
        db.ForeignKey("expense_plan_items.plan_item_id"),
        nullable=False,
        index=True,
    )
    user_id = db.Column(db.String(64), nullable=False)
    assigned_date = db.Column(db.Date, nullable=False)
    planned_amount = db.Column(db.BigInteger, nullable=False)
    priority = db.Column(db.String(2), nullable=False, default="P1")
    checkin_deadline_at = db.Column(db.DateTime, nullable=False)
    payment_due_date = db.Column(db.Date, nullable=True)
    task_status = db.Column(db.String(20), nullable=False, default="PENDING")
    checked_at = db.Column(db.DateTime, nullable=True)
    is_demo = db.Column(db.Boolean, nullable=False, default=True)
    created_at = db.Column(db.DateTime, nullable=False, default=utcnow)
    updated_at = db.Column(db.DateTime, nullable=False, default=utcnow, onupdate=utcnow)

    plan_item = db.relationship("ExpensePlanItem", back_populates="tasks")
    records = db.relationship("ExpenseRecord", back_populates="task")

    __table_args__ = (
        db.UniqueConstraint(
            "plan_item_id", "assigned_date", name="uq_assigned_task_plan_date"
        ),
        Index("ix_assigned_tasks_user_date", "user_id", "assigned_date"),
    )

    def __repr__(self) -> str:  # pragma: no cover - debugging helper
        return f"<AssignedExpenseTask {self.task_id} {self.assigned_date}>"


class ExpenseRecord(db.Model):
    """An actual expense, either linked to a task or unexpected."""

    __tablename__ = "expense_records"

    record_id = db.Column(db.String(21), primary_key=True)
    user_id = db.Column(db.String(64), nullable=False)
    task_id = db.Column(
        db.String(21),
        db.ForeignKey("assigned_expense_tasks.task_id"),
        nullable=True,
        index=True,
    )
    record_type = db.Column(db.String(20), nullable=False)
    amount = db.Column(db.BigInteger, nullable=False)
    expense_date = db.Column(db.Date, nullable=False)
    actual_amount_source = db.Column(db.String(20), nullable=True)
    title = db.Column(db.String(200), nullable=True)
    category = db.Column(db.String(80), nullable=True)
    note = db.Column(db.Text, nullable=True)
    idempotency_key = db.Column(db.String(64), nullable=True)
    is_demo = db.Column(db.Boolean, nullable=False, default=True)
    created_at = db.Column(db.DateTime, nullable=False, default=utcnow)
    updated_at = db.Column(db.DateTime, nullable=False, default=utcnow, onupdate=utcnow)

    task = db.relationship("AssignedExpenseTask", back_populates="records")

    __table_args__ = (
        Index("ix_expense_records_user_date", "user_id", "expense_date"),
        Index(
            "uq_expense_records_idempotency",
            "user_id",
            "idempotency_key",
            unique=True,
            postgresql_where=text("idempotency_key IS NOT NULL"),
            sqlite_where=text("idempotency_key IS NOT NULL"),
        ),
        Index(
            "uq_expense_records_planned_task",
            "task_id",
            unique=True,
            postgresql_where=text("task_id IS NOT NULL AND record_type = 'PLANNED'"),
            sqlite_where=text("task_id IS NOT NULL AND record_type = 'PLANNED'"),
        ),
    )

    def __repr__(self) -> str:  # pragma: no cover - debugging helper
        return f"<ExpenseRecord {self.record_id} {self.amount}>"
